//! Headless onboarding: render a `.env` from a preset (port of `cmd/onboard --preset --yes`).

use std::fmt::Write as _;
use std::path::PathBuf;

#[derive(Clone, Copy, clap::ValueEnum)]
enum Preset {
    /// Plaintext on localhost, debug logs.
    Minimal,
    /// Local TLS with a self-signed cert, info logs.
    Standard,
    /// Listen on all interfaces with real certs and a generated token secret.
    Production,
}

#[derive(clap::Args)]
pub struct Args {
    #[arg(long, value_enum, default_value = "standard")]
    preset: Preset,
    #[arg(long, default_value = ".env")]
    out: PathBuf,
    /// Overwrite an existing file.
    #[arg(long)]
    force: bool,
}

fn render(p: Preset, secret: &str) -> String {
    let (addr, log, tls) = match p {
        Preset::Minimal => ("127.0.0.1:8080", "debug", "# plaintext (h1 + h2c)"),
        Preset::Standard => ("127.0.0.1:8443", "info", "# run with: rb serve --self-signed"),
        Preset::Production => ("0.0.0.0:443", "info", "# run with: rb serve --cert /etc/rb/cert.pem --key /etc/rb/key.pem"),
    };
    let mut s = String::new();
    let _ = writeln!(s, "# Generated by `rb env`.");
    let _ = writeln!(s, "{tls}");
    let _ = writeln!(s, "RB_ADDR={addr}");
    let _ = writeln!(s, "RUST_LOG={log}");
    let _ = writeln!(s, "RB_TOKEN_SECRET={secret}");
    s
}

pub fn run(a: Args) -> anyhow::Result<()> {
    anyhow::ensure!(a.force || !a.out.exists(), "{} exists (pass --force to overwrite)", a.out.display());
    let secret = match a.preset {
        Preset::Production => {
            let mut bytes = [0u8; 32];
            ring::rand::SecureRandom::fill(&ring::rand::SystemRandom::new(), &mut bytes)
                .map_err(|_| anyhow::anyhow!("no system randomness"))?;
            bytes.iter().map(|b| format!("{b:02x}")).collect()
        }
        _ => "dev-secret-change-me".to_string(),
    };
    super::write_atomic(&a.out, render(a.preset, &secret).as_bytes())?;
    println!("wrote {}", a.out.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn presets_render_expected_keys() {
        let s = render(Preset::Minimal, "x");
        assert!(s.contains("RB_ADDR=127.0.0.1:8080") && s.contains("RB_TOKEN_SECRET=x"));
        assert!(render(Preset::Production, "y").contains("0.0.0.0:443"));
    }
}
